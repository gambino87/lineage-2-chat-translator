"""Real Windows RSA-PSS tests using disposable, non-production CNG keys."""
from __future__ import annotations

import base64
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest import mock
import uuid

import update_trust as trust

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("publisher_sign_release", ROOT / "packaging/sign_release.py")
signer = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(signer)


@unittest.skipUnless(os.name == "nt", "Windows platform cryptography")
class NativeReleaseSignatureTests(unittest.TestCase):
    @classmethod
    def _ps(cls, *arguments, success=True):
        result = subprocess.run(
            [str(signer._powershell()), "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", *arguments],
            capture_output=True, text=True, timeout=60, creationflags=subprocess.CREATE_NO_WINDOW,
        )
        if success and result.returncode:
            raise AssertionError(result.stderr)
        return result

    @classmethod
    def _helper(cls, mode, key, *arguments, success=True):
        return cls._ps("-File", str(signer.SIGNER), "-Mode", mode, "-KeyName", key,
                       *arguments, success=success)

    @classmethod
    def _delete_keys(cls):
        for key in cls.keys:
            # The prefix is generated by this fixture. Production keys cannot
            # enter this cleanup operation even if fixture creation fails.
            if not key.startswith("Lineage2ChatTranslator.TestSigning."):
                raise AssertionError("Unsafe test key cleanup")
            cls._ps("-Command", "$p=[System.Security.Cryptography.CngProvider]::MicrosoftSoftwareKeyStorageProvider; "
                    f"if ([System.Security.Cryptography.CngKey]::Exists('{key}',$p)) {{ "
                    f"$k=[System.Security.Cryptography.CngKey]::Open('{key}',$p); "
                    "try {$k.Delete()} finally {$k.Dispose()} }")

    @classmethod
    def setUpClass(cls):
        cls.keys = ["Lineage2ChatTranslator.TestSigning." + uuid.uuid4().hex for _ in range(2)]
        cls.temp = tempfile.TemporaryDirectory(prefix="l2ct-signature-test-")
        cls.directory = Path(cls.temp.name)
        cls.metadata = b'{"product":"Lineage 2 Chat Translator","version":"9.1.2"}\n'
        cls.input = cls.directory / "release.json"
        cls.input.write_bytes(cls.metadata)
        try:
            cls.records = [json.loads(cls._helper("Provision", key).stdout) for key in cls.keys]
            cls.blob = cls.records[0]["public_blob_b64"]
            cls.signatures = []
            for index, key in enumerate(cls.keys):
                output = cls.directory / f"signature-{index}"
                cls._helper("Sign", key, "-InputFile", str(cls.input), "-OutputFile", str(output))
                cls.signatures.append(output.read_bytes())
        except BaseException:
            cls._delete_keys()
            cls.temp.cleanup()
            raise

    @classmethod
    def tearDownClass(cls):
        cls._delete_keys()
        cls.temp.cleanup()

    def test_native_signature_and_pinned_entry_point(self):
        self.assertEqual(len(self.signatures[0]), trust.SIGNATURE_BYTES)
        trust._verify_with_key(self.metadata, self.signatures[0], self.blob)
        with mock.patch.object(trust, "PUBLIC_KEY_BLOB_B64", self.blob):
            trust.verify_release_signature(self.metadata, self.signatures[0])

    def test_changed_metadata_and_reserialization_are_rejected(self):
        for data in (self.metadata.replace(b"9.1.2", b"9.1.3"), self.metadata.rstrip(b"\n"),
                     self.metadata.replace(b":", b": ")):
            with self.subTest(data=data), self.assertRaises(trust.SignatureError):
                trust._verify_with_key(data, self.signatures[0], self.blob)

    def test_corrupt_signature_and_different_publisher_are_rejected(self):
        corrupt = bytearray(self.signatures[0])
        corrupt[100] ^= 1
        for signature in (bytes(corrupt), self.signatures[1], bytes(trust.SIGNATURE_BYTES)):
            with self.subTest(signature=signature[:8]), self.assertRaises(trust.SignatureError):
                trust._verify_with_key(self.metadata, signature, self.blob)

    def test_pinned_public_key_cannot_be_replaced_by_a_signature(self):
        with mock.patch.object(trust, "PUBLIC_KEY_BLOB_B64", self.records[1]["public_blob_b64"]):
            with self.assertRaises(trust.SignatureError):
                trust.verify_release_signature(self.metadata, self.signatures[0])

    def test_non_pss_signature_is_rejected(self):
        output = self.directory / "pkcs1.sig"
        key = self.keys[0]
        script = ("$p=[System.Security.Cryptography.CngProvider]::MicrosoftSoftwareKeyStorageProvider; "
                  f"$k=[System.Security.Cryptography.CngKey]::Open('{key}',$p); "
                  "$r=New-Object System.Security.Cryptography.RSACng($k); try {"
                  f"$d=[Convert]::FromBase64String('{base64.b64encode(self.metadata).decode('ascii')}'); "
                  "$s=$r.SignData($d,[System.Security.Cryptography.HashAlgorithmName]::SHA256,"
                  "[System.Security.Cryptography.RSASignaturePadding]::Pkcs1); "
                  f"[IO.File]::WriteAllBytes('{str(output).replace(chr(39), chr(39)*2)}',$s)"
                  "} finally {$r.Dispose(); $k.Dispose()}")
        self._ps("-Command", script)
        with self.assertRaises(trust.SignatureError):
            trust._verify_with_key(self.metadata, output.read_bytes(), self.blob)

    def test_key_is_non_exportable_current_user_signing_only(self):
        self.assertFalse(self.records[0]["exportable"])
        key = self.keys[0]
        result = self._ps("-Command", "$ErrorActionPreference='Stop'; "
                          "$p=[System.Security.Cryptography.CngProvider]::MicrosoftSoftwareKeyStorageProvider; "
                          f"$k=[System.Security.Cryptography.CngKey]::Open('{key}',$p); "
                          "try { $blocked=$false; try { $unused=$k.Export([System.Security.Cryptography.CngKeyBlobFormat]::GenericPrivateBlob) } "
                          "catch [System.Security.Cryptography.CryptographicException] {$blocked=$true}; "
                          "@{blocked=$blocked; machine=$k.IsMachineKey; policy=[int]$k.ExportPolicy; usage=[int]$k.KeyUsage} | ConvertTo-Json -Compress "
                          "} finally {$k.Dispose()}")
        details = json.loads(result.stdout)
        self.assertTrue(details["blocked"])
        self.assertFalse(details["machine"])
        self.assertEqual(details["policy"], 0)
        self.assertEqual(details["usage"], 2)

    def test_provision_never_replaces_existing_key(self):
        result = self._helper("Provision", self.keys[0], success=False)
        self.assertNotEqual(result.returncode, 0)
        current = json.loads(self._helper("Inspect", self.keys[0]).stdout)
        self.assertEqual(current["public_blob_b64"], self.blob)

    def test_signing_never_overwrites_existing_signature(self):
        output = self.directory / "signature-0"
        before = output.read_bytes()
        result = self._helper("Sign", self.keys[0], "-InputFile", str(self.input), "-OutputFile", str(output), success=False)
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(output.read_bytes(), before)

    def test_signer_rejects_oversized_metadata(self):
        source, output = self.directory / "oversized.json", self.directory / "oversized.sig"
        source.write_bytes(b"x" * (trust.MAX_METADATA_BYTES + 1))
        result = self._helper("Sign", self.keys[0], "-InputFile", str(source), "-OutputFile", str(output), success=False)
        self.assertNotEqual(result.returncode, 0)
        self.assertFalse(output.exists())

    def test_python_wrapper_verifies_exact_returned_signature(self):
        def fake_sign(arguments, **kwargs):
            source = Path(arguments[arguments.index("-InputFile") + 1])
            target = Path(arguments[arguments.index("-OutputFile") + 1])
            self.assertEqual(source.read_bytes(), self.metadata)
            target.write_bytes(self.signatures[0])
            return subprocess.CompletedProcess(arguments, 0, "{}", "")

        with mock.patch.object(signer.subprocess, "run", side_effect=fake_sign), \
                mock.patch.object(trust, "PUBLIC_KEY_BLOB_B64", self.blob):
            self.assertEqual(signer.sign_metadata(self.metadata), self.signatures[0])
        with mock.patch.object(signer.subprocess, "run", side_effect=fake_sign), \
                mock.patch.object(trust, "PUBLIC_KEY_BLOB_B64", self.records[1]["public_blob_b64"]):
            with self.assertRaises(trust.SignatureError):
                signer.sign_metadata(self.metadata)


class SignatureInputBoundsTests(unittest.TestCase):
    def test_bad_signature_lengths_and_metadata_types_fail_closed(self):
        cases = [(b"x", b""), (b"x", bytes(383)), (b"x", bytes(385)),
                 (b"", bytes(384)), (b"x" * 65537, bytes(384)),
                 ("x", bytes(384)), (bytearray(b"x"), bytes(384))]
        for data, signature in cases:
            with self.subTest(size=len(data)), self.assertRaises(trust.SignatureError):
                trust._verify_with_key(data, signature, "not a valid key")

    def test_malformed_or_private_key_blobs_are_rejected(self):
        for encoded in ("", "PENDING_PROVISION", "!!!!", base64.b64encode(bytes(411)).decode("ascii")):
            with self.subTest(encoded=encoded[:20]), self.assertRaises(trust.SignatureError):
                trust._public_blob(encoded)

    def test_signing_bounds_apply_before_starting_powershell(self):
        with mock.patch.object(signer.subprocess, "run") as run:
            for data in (b"", b"x" * 65537, "text"):
                with self.assertRaises(ValueError):
                    signer.sign_metadata(data)
            run.assert_not_called()


if __name__ == "__main__":
    unittest.main()
